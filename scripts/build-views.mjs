import { build } from 'esbuild';
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  entryPoints: [path.join(root, 'views/src/main.js')],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  target: 'es2022',
  legalComments: 'inline',
});
const template = await readFile(path.join(root, 'views/src/template.html'), 'utf8');
const style = await readFile(path.join(root, 'views/src/style.css'), 'utf8');
const script = result.outputFiles[0].text.replaceAll('</script', '<\\/script');
for (const view of ['viewer', 'inspector']) {
  const html = template.replace('/* STYLE */', () => style)
    .replace('/* SCRIPT */', () => script)
    .replace('VIEW_NAME', view)
    .replace('OTHER_VIEW_LABEL', view === 'viewer' ? 'Element inspector' : '3D viewer');
  await writeFile(path.join(root, `views/${view}.html`), `<!-- Generated by npm run build. Edit views/src/. -->\n${html}`);
}
await mkdir(path.join(root, 'assets/licenses'), { recursive: true });
await copyFile(path.join(root, 'node_modules/three/LICENSE'), path.join(root, 'assets/licenses/three-MIT.txt'));
console.log('Built self-contained viewer and inspector.');
